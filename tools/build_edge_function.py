#!/usr/bin/env python3
"""Builds supabase/functions/neet-ai/index.ts as ONE self-contained file (easy to paste into the Supabase dashboard editor).

It inlines the app's own prompt builder and AI provider code so the website and the Edge Function never drift apart.
Run after editing assets/js/prompts.js, assets/js/providers.js or tools/edge_handler.js:

    python3 tools/build_edge_function.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def module_body(path):
    src = (ROOT / path).read_text()
    if re.search(r"^\s*import\s", src, re.M):
        raise SystemExit(f"{path} must not import anything (it is inlined into the Edge Function)")
    return re.sub(r"^export\s+", "", src, flags=re.M)


handler = (ROOT / "tools/edge_handler.js").read_text()
imports = "\n".join(l for l in handler.splitlines() if l.startswith("import "))
handler_body = "\n".join(l for l in handler.splitlines() if not l.startswith("import "))

out = f"""// @ts-nocheck
// GENERATED by tools/build_edge_function.py — do not edit by hand.
// Supabase Edge Function "neet-ai": free AI for YourNEETBuddy visitors, with the Gemini key kept secret on the server.
{imports}

/* ---------------- assets/js/prompts.js ---------------- */
{module_body("assets/js/prompts.js")}
/* ---------------- assets/js/providers.js ---------------- */
{module_body("assets/js/providers.js")}
{handler_body}
"""

dest = ROOT / "supabase/functions/neet-ai/index.ts"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text(out)
print(f"Wrote {dest.relative_to(ROOT)} ({len(out.splitlines())} lines)")
